export type Bucket = { id:string; name:string; description?:string; type:'spending'|'saving'|'investment'|'other'; balanceCents:string; monthlyChangeCents:string; plannedExpenseCents?:string; currency:string; icon:string; color:string; monthlyTargetCents:string|null; sortOrder:number; includeInTotal:boolean };
export type Dashboard = { totalCents:string; monthlyChangeCents:string; buckets:Bucket[] };
export type OperationEntry = { bucketId:string; bucketName:string; bucketIcon:string; bucketType:Bucket['type']; amountCents:string; balanceAfterCents:string };
export type Operation = { id:string; kind:'adjustment'|'transfer'|'distribution'|'rebalance'; note:string|null; occurredAt:string; entries:OperationEntry[] };
export type TrendBucket = Pick<Bucket,'id'|'name'|'type'|'color'|'includeInTotal'> & { balanceCents:string };
export type TrendMonth = { month:string; totalCents:string; buckets:TrendBucket[] };
export type PlannedExpenseAmountMode = 'fixed'|'estimated';
export type PlannedExpenseFrequency = 'monthly'|'bimonthly'|'quarterly'|'semiannual'|'annual'|'once';
export type PlannedExpenseDueRule = 'month'|'exact'|'start'|'mid'|'end';
export type PlannedExpenseCategory = 'subscription'|'installment'|'one_time'|'other';
export type PlannedExpenseStatus = 'open'|'completed';
export type PlannedExpenseBase = {
  id:string;
  name:string;
  description:string|null;
  category:PlannedExpenseCategory;
  bucketId:string;
  bucketName:string;
  bucketIcon:string|null;
  bucketType:Bucket['type'];
  bucketColor:string|null;
  amountCents:string;
  configuredAmountCents:string;
  amountMode:PlannedExpenseAmountMode;
  frequency:PlannedExpenseFrequency;
  dueRule:PlannedExpenseDueRule;
  dueDay:number|null;
  dueDate:string|null;
  startMonth:string;
  durationMonths:number|null;
  archivedAt:string|null;
  includedInEstimatedTotal:boolean;
};
export type PlannedExpense = PlannedExpenseBase & {
  period:string;
  status:PlannedExpenseStatus;
  actualAmountCents:string;
  paymentCount:number;
  completedAt:string|null;
};
export type ManagedPlannedExpense = PlannedExpenseBase;
export type EndedPlannedExpense = PlannedExpenseBase & { endedReason:'archived'|'duration'|string };
export type PlannedExpensesResponse = { expenses:PlannedExpense[]; endedExpenses:EndedPlannedExpense[] };
export type PlannedExpenseInput = {
  name:string;
  description:string|null;
  category:PlannedExpenseCategory;
  bucketId:string;
  amountCents:string;
  amountMode:PlannedExpenseAmountMode;
  frequency:PlannedExpenseFrequency;
  dueRule:PlannedExpenseDueRule;
  dueDay:number|null;
  dueDate:string|null;
  startMonth:string;
  durationMonths:number|null;
};
export type CurrentUser = {
  id:string;
  email:string;
  role:'user'|'admin';
  firstName:string|null;
  lastName:string|null;
  gender:'male'|'female'|null;
  isActive:boolean;
  mustChangePassword:boolean;
  /** Changes whenever the profile photo changes; null without a photo. */
  avatarVersion?:string|null;
};
export type ManagedUser = CurrentUser & { createdAt:string };
